export function getMesocycleForWeek(week: number) {
  return MESOCYCLES.find((m) => m.weeks.includes(week)) ?? MESOCYCLES[0];
}

export function getMesocycleIndexForWeek(week: number): number {
  if (week === 0) return 0;
  if (week >= 1 && week <= 4) return 1;
  if (week === 5) return 1; // deload uses M1 exercises
  if (week >= 6 && week <= 8) return 2;
  if (week === 9) return 2; // deload uses M2 exercises
  if (week >= 10 && week <= 12) return 3;
  return 1;
}

